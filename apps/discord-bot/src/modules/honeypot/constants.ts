export function containsBadWord(text: string): string | null {
  const words = text
    .toLowerCase()
    .replace(/[^a-z0-9]/gi, ' ')
    .split(/\W+/)
    .filter(Boolean);
  return words.find((w) => DISALLOWED_WORDS.includes(w)) || null;
}
